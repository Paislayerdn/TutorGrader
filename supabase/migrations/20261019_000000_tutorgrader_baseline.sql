            RAISE EXCEPTION 'current_draft_number must reference an existing problem version';
        END IF;

        IF target_status <> 'DRAFT' THEN
            RAISE EXCEPTION 'current_draft_number must reference a DRAFT version';
        END IF;
    END IF;

    RETURN NEW;
END;
