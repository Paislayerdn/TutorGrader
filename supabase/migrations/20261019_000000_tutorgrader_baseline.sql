CREATE OR REPLACE FUNCTION public.prevent_published_version_child_change()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO ''
AS $function$
BEGIN
    IF TG_OP <> 'INSERT' AND EXISTS (
        SELECT 1
        FROM public.problem_version AS pv
